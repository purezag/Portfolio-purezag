const SPLIT = '[data-loader-line], [data-hero-title], [data-hero-sub], [data-claim], [data-finale-title], [data-fit-one], [data-lines-title], [data-statement], [data-notes-title], [data-roll]';
const ATTRS = ['aria-label', 'alt', 'title', 'data-name'];
const STORE = 'ohmen-lang';

const normal = value => value.replace(/\s+/g, ' ').trim();

function translateText(value, lang, table = PT) {
  if (lang === 'en') return value;
  const key = normal(value);
  if (!key || !(key in table)) return value;
  const lead = value.match(/^\s*/)[0];
  const tail = value.match(/\s*$/)[0];
  return lead + table[key] + tail;
}

function translateTree(root, lang) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach(node => { node.nodeValue = translateText(node.nodeValue, lang); });
  root.querySelectorAll('*').forEach(el => {
    ATTRS.forEach(attr => {
      if (el.hasAttribute(attr)) el.setAttribute(attr, translateText(el.getAttribute(attr), lang));
    });
  });
}

export class I18n {
  constructor() {
    this.lang = 'en';
    this.nodes = [];
    this.attrs = [];
    this.snaps = [];
  }

  static initial() {
    try {
      const forced = new URLSearchParams(window.location.search).get('lang');
      if (forced === 'pt' || forced === 'en') return forced;
      const saved = localStorage.getItem(STORE);
      if (saved === 'pt' || saved === 'en') return saved;
    } catch (error) {
      return 'en';
    }
    return 'en';
  }

  capture(root = document.body) {
    const splits = [...root.querySelectorAll(SPLIT)];
    this.snaps = splits.map(el => {
      const en = el.innerHTML;
      const tpl = document.createElement('template');
      tpl.innerHTML = en;
      translateTree(tpl.content, 'pt');
      return { el, en, pt: tpl.innerHTML };
    });
    const inSplit = node => splits.some(el => el !== node && el.contains(node));
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode: node => {
        const parent = node.parentElement;
        if (!parent || parent.closest('script, style, svg, template')) return NodeFilter.FILTER_REJECT;
        if (!(normal(node.nodeValue) in PT)) return NodeFilter.FILTER_SKIP;
        if (inSplit(node)) return NodeFilter.FILTER_SKIP;
        return NodeFilter.FILTER_ACCEPT;
      }
    });
    while (walker.nextNode()) this.nodes.push({ node: walker.currentNode, en: walker.currentNode.nodeValue });
    root.querySelectorAll('*').forEach(el => {
      if (splits.some(s => s.contains(el) && s !== el)) return;
      ATTRS.forEach(attr => {
        if (!el.hasAttribute(attr)) return;
        const value = el.getAttribute(attr);
        if (normal(value) in PT) this.attrs.push({ el, attr, en: value });
      });
    });
  }

  apply(lang) {
    this.lang = lang;
    document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';
    this.snaps.forEach(snap => { snap.el.innerHTML = snap[lang]; });
    this.nodes.forEach(item => { item.node.nodeValue = translateText(item.en, lang); });
    this.attrs.forEach(item => { item.el.setAttribute(item.attr, translateText(item.en, lang)); });
    document.querySelectorAll('[data-lang-toggle]').forEach(button => {
      button.dataset.lang = lang;
      button.setAttribute('aria-label', UI[lang].switchTo);
      button.querySelectorAll('[data-l]').forEach(label => label.classList.toggle('is-on', label.dataset.l === lang));
    });
    try {
      localStorage.setItem(STORE, lang);
    } catch (error) {
      return;
    }
  }

  ui(key, ...args) {
    const value = UI[this.lang][key];
    return typeof value === 'function' ? value(...args) : value;
  }

  word(value) {
    if (this.lang === 'en') return value;
    return OPTION_PT[value] || PT[value] || value;
  }
}
